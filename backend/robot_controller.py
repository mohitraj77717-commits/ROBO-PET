# backend/robot_controller.py — Robot Action & State Coordination

import logging
from typing import Dict, Any, Optional
from backend.validator import validator
from backend.serial_manager import SerialManager
from backend.timer_manager import timer_manager
from backend.config import Config

logger = logging.getLogger("RoboPet.RobotController")

class RobotController:
    def __init__(self):
        self.timer_mgr = timer_manager
        
        # Link serial manager
        self.serial_mgr = SerialManager()
        
        # Register timer expire callback
        self.timer_mgr.on_timer_expire = self._handle_timer_expired

        # Current state
        self.current_emotion = "neutral"
        self.current_action: Optional[str] = None
        self.current_display = "time"
        self.battery = Config.SIMULATED_BATTERY

    def _handle_timer_expired(self, label: str):
        """Called when a timer reaches 0."""
        logger.info(f"Triggering alert for expired timer: {label}")
        self.execute_command("wiggle", "movements")
        self.serial_mgr.send_command({
            "type": "alert",
            "reason": "timer_expired",
            "label": label
        })

    def execute_ai_intent(self, ai_output: Dict[str, Any]) -> Dict[str, Any]:
        """
        Execute the structured output generated by Gemini AI.
        Dispatches validated emotion and action to the ESP32.
        """
        emotion = validator.validate_emotion(ai_output.get("emotion"))
        action = validator.validate_action(ai_output.get("action"))
        display_action = validator.validate_display_action(ai_output.get("display_action"))

        self.current_emotion = emotion
        if action:
            self.current_action = action
        if display_action:
            self.current_display = display_action

        # Dispatch command to ESP32
        payload = {
            "type": "cmd",
            "emotion": emotion,
            "action": action
        }
        if display_action:
            payload["display"] = display_action

        self.serial_mgr.send_command(payload)

        # Check if conversation requested setting a countdown timer
        import re
        user_msg = (ai_output.get("metadata", {}).get("user_message") or "").lower()
        resp_text = (ai_output.get("response") or "").lower()
        combined = f"{user_msg} {resp_text}"
        timer_match = re.search(r'(?:timer|countdown)(?:\s+of|\s+for)?\s+(\d+)\s*(sec|second|min|minute)?', combined)
        if timer_match:
            amount = int(timer_match.group(1))
            unit = (timer_match.group(2) or "sec").lower()
            duration_sec = amount * 60 if "min" in unit else amount
            if not self.timer_mgr.is_active:
                self.timer_mgr.set_timer(duration_sec, f"{amount} {unit} Timer")

        return {
            "response": ai_output.get("response", ""),
            "emotion": emotion,
            "action": action,
            "metadata": ai_output.get("metadata", {})
        }

    def execute_command(self, command_name: str, category: Optional[str] = None) -> Dict[str, Any]:
        """
        Execute a validated manual command from frontend POST /command.
        Returns: { success: bool, message: str, emotion: str, action: str|None }
        """
        is_valid, resolved_cat, meta = validator.validate_manual_command(command_name, category)
        if not is_valid:
            logger.warning(f"Rejected unvalidated command: '{command_name}' (category: '{category}')")
            return {
                "success": False,
                "message": f"Command '{command_name}' is not recognized or not permitted.",
                "emotion": self.current_emotion,
                "action": None
            }

        cmd_lower = command_name.lower().strip()
        emotion = self.current_emotion
        action = None
        message = f"Executed {cmd_lower}."

        # Handle Emotions
        if resolved_cat == "emotions":
            emotion = cmd_lower
            self.current_emotion = emotion
            message = f"Expression set to {cmd_lower}!"
            self.serial_mgr.send_command({"type": "cmd", "emotion": emotion})

        # Handle Movements (dance, nod, shake, look, wave, wiggle)
        elif resolved_cat == "movements":
            action = validator.validate_action(cmd_lower) or cmd_lower
            self.current_action = action
            emotion = "happy" if action in ("dance", "wave", "wiggle") else self.current_emotion
            self.current_emotion = emotion
            message = f"Performing movement: {action.replace('_', ' ')}!"
            self.serial_mgr.send_command({
                "type": "cmd",
                "action": action,
                "emotion": emotion
            })

        # Handle Display Actions
        elif resolved_cat == "display":
            self.current_display = cmd_lower
            message = f"ESP32 OLED Display updated: {cmd_lower.replace('_', ' ')}."
            self.serial_mgr.send_command({"type": "display", "mode": meta.get("screen_mode", cmd_lower)})

        # Handle Utilities
        elif resolved_cat == "utilities":
            if cmd_lower == "reset_expression":
                self.current_emotion = "neutral"
                emotion = "neutral"
                message = "Expression reset to neutral."
                self.serial_mgr.send_command({"type": "cmd", "emotion": "neutral", "action": "look"})
            elif cmd_lower == "show_battery":
                message = f"Current battery level: {self.battery}%"
            elif cmd_lower == "status":
                status_summary = "ESP32 Linked" if self.serial_mgr.is_connected else "ESP32 Virtual Simulation"
                message = f"Robot Diagnostics: Status Online | {status_summary} | Battery {self.battery}%"

        # Handle Conversation triggers
        elif resolved_cat == "conversation":
            message = meta.get("description", f"Conversation trigger: {cmd_lower}")
            emotion = "happy"

        return {
            "success": True,
            "message": message,
            "emotion": emotion,
            "action": action,
            "command": cmd_lower,
            "category": resolved_cat
        }

    def get_full_status(self) -> Dict[str, Any]:
        """
        Assemble the complete status snapshot required by frontend GET /status.
        """
        timer_status = self.timer_mgr.get_status()

        return {
            "status": "online",
            "esp32_connected": self.serial_mgr.is_connected or self.serial_mgr.is_simulated,
            "hardware_mode": "physical" if self.serial_mgr.is_connected else "simulated",
            "battery": self.battery,
            "timer": timer_status,
            "state": {
                "emotion": self.current_emotion,
                "action": self.current_action,
                "display": self.current_display
            }
        }

# Global singleton
robot_controller = RobotController()
